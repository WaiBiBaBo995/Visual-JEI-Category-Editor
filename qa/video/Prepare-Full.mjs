import fs from 'node:fs';
import path from 'node:path';
const dir='video-production/full';
if(fs.existsSync(path.join(dir,'film.html')))throw new Error('Preserve existing full-film edits.');
for(const folder of ['assets/video','assets/audio/vo','assets/honghe'])fs.mkdirSync(path.join(dir,folder),{recursive:true});
const text=fs.readFileSync('docs/video/VJCE-AI配音稿.txt','utf8').replace(/^\uFEFF/,'');
const paragraphs=text.trim().split(/\r?\n\s*\r?\n/);
paragraphs[6]=paragraphs[6].replace('整个结构就进到页面里了','选区里的结构就进到页面里了');
paragraphs[13]='本次演示使用 Minecraft 一点二十一点一，运行还需要 NeoForge、JEI 和 LDLib2。它编辑的是 JEI 展示，实际加工规则仍由原模组或整合包决定。第三方页面能编辑到哪一步，也取决于适配情况。';
paragraphs[14]='想给整合包做一张这样的说明页，可以先从这个示例工程改起，再做成自己的样子。这就是 VJCE。';
const durations=[12,18,18,20,20,22,30,18,15,15,10,24,16,15,17];
let start=0;
const rows=paragraphs.map((text,i)=>{const row={id:`S${String(i+1).padStart(2,'0')}`,start,duration:durations[i],text,sentences:text.match(/[^。！？]+[。！？]?/g).map(s=>s.trim()).filter(Boolean)};start+=row.duration;return row;});
fs.writeFileSync(path.join(dir,'narration.json'),JSON.stringify(rows,null,2));
fs.writeFileSync(path.join(dir,'配音稿.txt'),paragraphs.join('\n\n')+'\n');
for(const file of ['Crafting_Table.png','Iron_Ingot.png','Writable_Book.png','146-copper-checker-alpha-60.webm'])fs.copyFileSync(path.join('video-production/sample-v2/assets/honghe',file),path.join(dir,'assets/honghe',file));
fs.copyFileSync('video-production/sample-v2/identity.css',path.join(dir,'identity.css'));
fs.copyFileSync('video-production/sample-v2/title-motion.js',path.join(dir,'title-motion.js'));
fs.copyFileSync('outputs/honghemc-assets/素材清单.md',path.join(dir,'honghe-素材来源.md'));
console.log(JSON.stringify({paragraphs:rows.length,sentences:rows.reduce((n,r)=>n+r.sentences.length,0),duration:start}));
